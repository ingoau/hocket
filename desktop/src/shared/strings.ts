export function t(id: StringId, params?: Record<string, string | number>): string {
  const raw: string = STRINGS[id];
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const v = params[key];
    return v === undefined ? `{${key}}` : String(v);
  });
}

export function hasString(id: string): id is StringId {
  return Object.prototype.hasOwnProperty.call(STRINGS, id);
}
